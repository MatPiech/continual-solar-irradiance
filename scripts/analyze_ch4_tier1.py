"""Phase 4 analysis for the Chapter 4 Tier 1 campaign (plan section 7).

Reads only results/ch4/tier1/ and writes tables/ch4_*.csv.  Every estimator comes
from cirr.fl.analysis, so Chapter 4 and Chapter 5 cannot disagree about what a
bootstrap interval or a Diebold-Mariano p-value means.  The one deliberate
difference is the equivalence margin: Chapter 5 tests +/-2 % against Isolated,
Chapter 4 tests +/-5 % against sliding-window adaptation (plan H4.1), so the
margin is applied here to the 90 % interval the shared code returns.

    python scripts/analyze_ch4_tier1.py
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from cirr.evaluation.campaign import PERIOD_SCALE, load_campaign_days
from cirr.evaluation.smart_persistence import predict_periods
from cirr.fl.analysis import W, contrast, holm, pooled
from cirr.utils.metrics import compute_metrics

ROOT = Path(__file__).resolve().parent.parent
T1 = ROOT / "results" / "ch4" / "tier1"
# The head-only ablation (plan section 6.2 of CH4_ANALYSIS_REPORT) runs the same
# policy with --t2 1e9, so every triggered update stays in the head.  It lives
# outside tier1/ because it is not part of the pre-registered main comparison.
ABLATION = ROOT / "results" / "ch4" / "ablation"
OUT = ROOT / "tables"

SITES = ["folsom", "karpicko", "poznan"]
METHODS = [
    "baseline",
    "memo_reg_all",
    "note_reg_all",
    "sm_rls",
    "sliding_window",
    "fewshot_d1",
    "fewshot_d7",
    "conditional",
    "conditional_headonly",
]
LABEL = {
    "baseline": "Static model",
    "memo_reg_all": "MEMO",
    "note_reg_all": "NOTE",
    "sm_rls": "RLS",
    "sliding_window": "Window",
    "fewshot_d1": "Few-shot 1d",
    "fewshot_d7": "Few-shot 7d",
    "conditional": "Conditional (full model)",
    "conditional_headonly": "Conditional (head only)",
}
ROOT_OF = {"conditional_headonly": ABLATION}
VARIANTS = ["conditional", "conditional_headonly"]
REFERENCE = "sliding_window"  # the strongest published comparator (plan H4.1)
TOST_MARGIN = 5.0  # per cent relative MAE


def seeds(site: str, method: str) -> list[str]:
    d = ROOT_OF.get(method, T1) / site / method
    return sorted(p.name for p in d.iterdir() if (p / "summary.json").exists()) if d.exists() else []


def daily(site: str, method: str) -> tuple[pd.DataFrame, int]:
    """Seed-averaged per-day metrics, in the shape cirr.fl.analysis expects."""
    frames = []
    for s in seeds(site, method):
        d = pd.read_csv(ROOT_OF.get(method, T1) / site / method / s / "metrics_daily.csv", dtype={"date": str})
        d = d.dropna(subset=["mae"])
        d = d[d.n_samples > 0].copy()
        d["mse"] = d.rmse**2
        d["sp_mse"] = d.sp_rmse**2
        frames.append(d)
    if not frames:
        return pd.DataFrame(), 0
    return pd.concat(frames).groupby("date", as_index=False).mean(numeric_only=True), len(frames)


def smart_persistence(site: str) -> pd.DataFrame:
    """Smart Persistence on exactly the scored population, all four metrics.

    The runs store only sp_rmse per day, so MAE, WAPE and SMAPE are recomputed
    here.  The baseline is deterministic given the periods and the clear-sky
    lookup, and the recomputed RMSE is asserted against what the runs recorded.
    """
    data = load_campaign_days(ROOT / "data" / f"{site}_prepared")
    rows = []
    for day in data.days:
        periods = [data.dataset.periods[j] for j in data.day_map[day]]
        preds, tgts, _ = predict_periods(periods, data.lookup, period_scale=PERIOD_SCALE)
        m = compute_metrics(preds, tgts)
        rows.append(
            dict(
                date=day,
                n_samples=m["count"],
                mae=m["mae"],
                rmse=m["rmse"],
                wape=m["wape"],
                smape=m["smape"],
                sp_rmse=m["rmse"],
            )
        )
    d = pd.DataFrame(rows)
    d["mse"] = d.rmse**2
    d["sp_mse"] = d.sp_rmse**2

    ref, _ = daily(site, "baseline")
    j = d.merge(ref[["date", "sp_rmse"]], on="date", suffixes=("", "_run"))
    assert np.allclose(j.sp_rmse, j.sp_rmse_run, atol=1e-9), f"{site}: recomputed SP disagrees with the runs"
    return d


def main() -> None:
    OUT.mkdir(exist_ok=True)

    # --- main comparison ---------------------------------------------------
    arms, main_rows = {}, []
    for site in SITES:
        sp = smart_persistence(site)
        arms[(site, "sp")] = sp
        p = pooled(sp)
        main_rows.append(dict(site=site, method="Persistence", seeds=0, **p))
        for m in METHODS:
            d, n = daily(site, m)
            if d.empty:
                continue
            arms[(site, m)] = d
            main_rows.append(dict(site=site, method=LABEL[m], seeds=n, **pooled(d)))
    main = pd.DataFrame(main_rows)
    main.to_csv(OUT / "ch4_main.csv", index=False)

    # the replacement for tab:ch4-solar-benchmark, on the lit population
    tex = [
        "% generated by scripts/analyze_ch4_tier1.py -- do not edit by hand",
        r"\begin{tabular}{@{}l l S S S S S@{}}",
        r"\toprule",
        r"Site & Method & {MAE} & {RMSE} & {WAPE} & {SMAPE} & {FS} \\",
        r"\midrule",
    ]
    for site in SITES:
        block = main[main.site == site]
        for i, (_, r) in enumerate(block.iterrows()):
            head = site.capitalize() if i == 0 else ""
            tex.append(f"{head} & {r.method} & {r.mae:.2f} & {r.rmse:.2f} & {r.wape:.2f} & {r.smape:.2f} & {r.fs:.2f} \\\\")
        tex.append(r"\midrule" if site != SITES[-1] else r"\bottomrule")
    tex.append(r"\end{tabular}")
    (OUT / "ch4_main.tex").write_text("\n".join(tex) + "\n")

    # --- H4.1 equivalence against the strongest comparator ------------------
    eq_rows = []
    for site in SITES:
        for v in VARIANTS:
            if (site, v) not in arms:
                continue
            c = contrast(arms[(site, v)], arms[(site, REFERENCE)], tag=f"{site}-h41-{v}")
            inside = c["rel_lo"] > -TOST_MARGIN and c["rel_hi"] < TOST_MARGIN
            eq_rows.append(
                dict(
                    site=site,
                    variant=LABEL[v],
                    rel_mae_pct=c["rel"],
                    ci90_lo=c["rel_lo"],
                    ci90_hi=c["rel_hi"],
                    margin=TOST_MARGIN,
                    equivalent=inside,
                    dfs=c["dfs"],
                    dfs_lo=c["dfs_lo"],
                    dfs_hi=c["dfs_hi"],
                    n_days=c["n_days"],
                )
            )
    eq = pd.DataFrame(eq_rows)
    eq.to_csv(OUT / "ch4_equivalence.csv", index=False)

    # --- pairwise contrasts, Holm across the whole family -------------------
    # One Holm family over both variants: every contrast reported is corrected
    # against every other one, including full model against head only.
    dm_rows = []
    for site in SITES:
        for v in VARIANTS:
            if (site, v) not in arms:
                continue
            for m in METHODS:
                if m == v or (site, m) not in arms or (m in VARIANTS and VARIANTS.index(m) < VARIANTS.index(v)):
                    continue
                c = contrast(arms[(site, v)], arms[(site, m)], tag=f"{site}-{v}-{m}")
                dm_rows.append(
                    dict(
                        site=site,
                        variant=LABEL[v],
                        against=LABEL[m],
                        rel_mae_pct=c["rel"],
                        ci90_lo=c["rel_lo"],
                        ci90_hi=c["rel_hi"],
                        dfs=c["dfs"],
                        p=c["p"],
                    )
                )
    dm = pd.DataFrame(holm(dm_rows))
    dm.to_csv(OUT / "ch4_dm.csv", index=False)

    # --- action mix and update cost ----------------------------------------
    act_rows = []
    for site in SITES:
        for v in VARIANTS:
            f = ROOT_OF.get(v, T1) / site / v / "seed0" / "events.csv"
            if not f.exists():
                continue
            e = pd.read_csv(f)
            tot = {a: int(e[a].sum()) for a in ("none", "head", "whole")}
            considered = int(e["considered"].sum())
            act_rows.append(
                dict(
                    site=site,
                    variant=LABEL[v],
                    considered=considered,
                    **tot,
                    head_pct=100 * tot["head"] / considered,
                    whole_pct=100 * tot["whole"] / considered,
                    update_rate_pct=100 * (tot["head"] + tot["whole"]) / considered,
                    clamp_sentinel=int(e.get("scope_changed_if_raw", pd.Series([0])).sum()),
                    updates_per_day=(tot["head"] + tot["whole"]) / len(e),
                )
            )
    pd.DataFrame(act_rows).to_csv(OUT / "ch4_actions.csv", index=False)

    # --- H4.4 retention -----------------------------------------------------
    ret_rows = []
    for site in SITES:
        f = T1 / site / "conditional" / "seed0" / "retention.json"
        if not f.exists():
            continue
        r = json.loads(f.read_text())
        s = r.get("source_stream")
        if s:
            ret_rows.append(
                dict(
                    site=site,
                    reference="source (Folsom)",
                    frozen_mae=s["frozen"]["mae"] * W,
                    adapted_mae=s["adapted"]["mae"] * W,
                    change_pct=100 * (s["adapted"]["mae"] / s["frozen"]["mae"] - 1),
                    n_days=s.get("n_days"),
                )
            )
    pd.DataFrame(ret_rows).to_csv(OUT / "ch4_retention.csv", index=False)

    # --- seed spread, for the arms that have more than one ------------------
    sd_rows = []
    for site in SITES:
        for m in ("fewshot_d1", "fewshot_d7"):
            vals = [json.loads((T1 / site / m / s / "summary.json").read_text())["pooled"]["mae"] * W for s in seeds(site, m)]
            if len(vals) > 1:
                sd_rows.append(
                    dict(
                        site=site,
                        method=LABEL[m],
                        n_seeds=len(vals),
                        mean_mae=float(np.mean(vals)),
                        sd_mae=float(np.std(vals, ddof=1)),
                        spread_mae=float(max(vals) - min(vals)),
                    )
                )
    pd.DataFrame(sd_rows).to_csv(OUT / "ch4_seed_spread.csv", index=False)

    # --- console summary ----------------------------------------------------
    pd.set_option("display.width", 200)
    for site in SITES:
        print(f"\n=== {site} ===")
        t = main[main.site == site][["method", "mae", "rmse", "wape", "smape", "fs", "seeds"]]
        print(t.to_string(index=False, float_format=lambda x: f"{x:.2f}"))
    print("\n=== H4.1: Conditional variants vs Window, 90 % CI on relative MAE, margin +/-5 % ===")
    print(
        eq[["site", "variant", "rel_mae_pct", "ci90_lo", "ci90_hi", "equivalent"]].to_string(
            index=False, float_format=lambda x: f"{x:.2f}"
        )
    )
    print("\n=== Pairwise (Holm-adjusted) ===")
    print(
        dm[["site", "variant", "against", "rel_mae_pct", "dfs", "p", "p_holm"]].to_string(
            index=False, float_format=lambda x: f"{x:.4f}"
        )
    )
    print("\nwrote", ", ".join(sorted(p.name for p in OUT.glob("ch4_*.csv"))))


if __name__ == "__main__":
    main()
